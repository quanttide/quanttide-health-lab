def canonical(label: str) -> tuple[str, bool]:
    """返回 (归并组名或原短语, 是否归并成功)。最长关键词优先，长度相同按表内顺序。"""
    text = label.strip()
    best: tuple[str, int] | None = None
    for name, words in GROUPS:
        for w in words:
            if w and w in text:
                if best is None or len(w) > best[1]:
                    best = (name, len(w))
    if best is None:
        return text, False
    return best[0], True


