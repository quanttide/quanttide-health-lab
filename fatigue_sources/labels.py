def actor_of(label: str) -> str:
    """判断这条来源的消耗是谁造成的。判不出就返回「双方共有或不明」，不硬派。"""
    text = label.strip()
    best: tuple[str, int] | None = None
    for name, words in ACTOR_RULES:
        for w in words:
            if w and w in text:
                if best is None or len(w) > best[1]:
                    best = (name, len(w))
    return best[0] if best else "双方共有或不明"
